import { chromium } from 'playwright-core' /* npm i -D playwright-core ; nécessite Chrome */;
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
p.on('pageerror', e => console.log('ERR', e.message)); p.on('console', m => m.type()==='error' && console.log('CONSOLE', m.text()));
const D='/workspace/robotics-ai-lab/';
await p.goto('http://localhost:4173/#/'); await p.waitForTimeout(800);
await p.click('.ex >> nth=1'); await p.waitForTimeout(300);
await p.screenshot({ path: D+'screenshot-home.png', fullPage: false });
console.log('nl:', (await p.textContent('#nlout')).slice(0,300));
await p.goto('http://localhost:4173/#/bibliotheque'); await p.waitForTimeout(1500); await p.screenshot({ path: D+'screenshot-library.png' });
console.log('cards', await p.locator('.rcard').count());
await p.goto('http://localhost:4173/#/robot/multirotor'); await p.waitForTimeout(1000); await p.screenshot({ path: D+'screenshot-detail.png' });
await p.goto('http://localhost:4173/#/atelier/wheeled'); await p.waitForTimeout(800); await p.fill('[data-k=mu]','0.1'); await p.dispatchEvent('[data-k=mu]','change'); await p.click('#mrun'); await p.waitForTimeout(500);
await p.screenshot({ path: D+'screenshot-workspace.png' });
console.log('ws:', (await p.textContent('#mres')).slice(0,400));
await p.goto('http://localhost:4173/#/atelier/aquatic'); 
await p.goto('http://localhost:4173/#/atelier/arm'); await p.waitForTimeout(1200); await p.fill('#scrub','100'); await p.dispatchEvent('#scrub','input'); await p.waitForTimeout(500);
await p.screenshot({ path: D+'screenshot.png' });
await b.close();
